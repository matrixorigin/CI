"""Same accepted PR execution, isolated explicit environment/node-pair routing."""
import yaml
import build_real_pr_node_cache_workflow as accepted

TARGET='.github/workflows/node-cache-all-env-real-pr-validation.yaml'


def build():
    value=accepted.build();value['name']='Isolated current PR full UT - explicit environment two groups'
    inputs=value['on']['workflow_call']['inputs']
    inputs.update(environment={'type':'string','required':True},node_pair={'type':'string','default':'01'})
    gate=value['jobs']['check_coverage_eligibility']
    gate['steps'].insert(0,{'name':'Validate explicit isolated environment and node pair',
        'env':{'CACHE_ENVIRONMENT':'${{ inputs.environment }}','NODE_PAIR':'${{ inputs.node_pair }}'},
        'run':'set -euo pipefail\ncase "$CACHE_ENVIRONMENT" in mty|jed|mnl2|ruh) ;; *) exit 1 ;; esac\n'
            'case "$NODE_PAIR" in 01|12) ;; *) exit 1 ;; esac\n'})
    job=value['jobs']['ut-coverage-linux-x86']
    job['runs-on']="${{ format('cs-{0}-nc-n{1}-pr-v1', inputs.environment, inputs.node_pair == '12' && (matrix.group == 0 && '1' || '2') || matrix.group) }}"
    # Per-group ordinary execution already verifies actual CS_CACHE_ENV equals
    # the environment-local S3 configuration; add explicit dispatch binding too.
    step=next(s for s in job['steps'] if s.get('id')=='node_cache')
    step['env']['REQUESTED_READER_ENVIRONMENT']='${{ inputs.environment }}'
    step['run']=step['run'].replace('set -euo pipefail\n',
        'set -euo pipefail\ntest "$CS_CACHE_ENV" = "$REQUESTED_READER_ENVIRONMENT"\n',1)
    return value


def render():
    return '# Generated by scripts/build_all_env_real_pr_workflow.py; isolated manual validation only.\n'+yaml.dump(
        build(),Dumper=accepted.consumer.Dumper,sort_keys=False,width=120)


if __name__=='__main__':print(render(),end='')
