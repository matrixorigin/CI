"""Identical full PR execution with independently reviewed PVC authorization."""
import yaml
import build_all_env_real_pr_workflow as previous

TARGET='.github/workflows/node-cache-persistent-real-pr-validation.yaml'


def build():
    value=previous.build();value['name']='Persistent PVC authority - real PR full two-group validation'
    gate=value['jobs']['check_coverage_eligibility']
    gate['steps'].insert(2,{'name':'Require live persistent publication metadata before allocating CS runners',
        'env':{'CS_CACHE_READ_TOKEN':'${{ secrets.CS_COVERAGE_CACHE_READ_TOKEN || github.token }}'},
        'run':'python3 .ci-workflow/scripts/node_cache_pvc_authority.py preflight'})
    job=value['jobs']['ut-coverage-linux-x86']
    step=next(s for s in job['steps'] if s.get('id')=='node_cache')
    before='node_cache_pr_native_catalog.py materialize'
    assert step['run'].count(before)==1
    step['run']=step['run'].replace(before,'node_cache_pvc_authority.py materialize')
    before='--catalog "$RUNNER_TEMP/cs-reviewed-native-catalog.json"'
    assert step['run'].count(before)==1
    step['run']=step['run'].replace(before,'--catalog "$RUNNER_TEMP/cs-reviewed-persistent-catalog.json"')
    report=next(s for s in job['steps'] if s.get('with',{}).get('name','').startswith('ut-coverage-report-'))
    report['with']['path']+='${{ runner.temp }}/cs-reviewed-persistent-catalog.json\n${{ runner.temp }}/cs-node-cache/persistent-authorization.json\n'
    return value


def render():
    return '# Generated by scripts/build_persistent_real_pr_workflow.py; original UT/resource contracts unchanged.\n'+yaml.dump(
        build(),Dumper=previous.accepted.consumer.Dumper,sort_keys=False,width=120)


if __name__=='__main__':print(render(),end='')
