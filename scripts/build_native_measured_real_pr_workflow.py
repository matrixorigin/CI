"""New opt-in workflow; protect existing persistent workflow and its test contracts."""
import yaml
import build_persistent_real_pr_workflow as parent

TARGET='.github/workflows/node-cache-native-measured-real-pr.yaml'


def build():
    value=parent.build()
    value['name']='Audited native PVC - measured real PR full two-group validation'
    job=value['jobs']['ut-coverage-linux-x86']
    steps=value['jobs']['check_coverage_eligibility']['steps']+job['steps']
    for old,new in [('node_cache_pvc_authority.py preflight','node_cache_native_pvc_catalog.py preflight'),
                    ('node_cache_pvc_authority.py materialize','node_cache_native_pvc_catalog.py materialize'),
                    ('/.ci-workflow/scripts/run_coverage_packages.py','/.ci-workflow/scripts/run_measured_coverage_packages.py')]:
        matches=[s for s in steps if old in s.get('run','')]
        if len(matches)!=1 or matches[0]['run'].count(old)!=1:raise ValueError('parent workflow changed')
        matches[0]['run']=matches[0]['run'].replace(old,new)
    upload=next(s for s in job['steps'] if s.get('id')=='upload_coverage_report')
    upload['with']['path']+='${{ runner.temp }}/go-rebuild-counts.json\n'
    return value


def render():
    return '# Generated by scripts/build_native_measured_real_pr_workflow.py\n'+yaml.dump(
        build(),Dumper=parent.previous.accepted.consumer.Dumper,sort_keys=False,width=120)


if __name__=='__main__': print(render(),end='')
