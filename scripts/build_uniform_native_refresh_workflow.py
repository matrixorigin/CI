"""Native-only preparation for one uniform environment CPU, separate from PR UT."""
import copy
import yaml
import build_native_refresh_workflow as old

TARGET='.github/workflows/node-cache-uniform-native-refresh.yaml'


def build():
    value=copy.deepcopy(old.build());value['name']='Uniform-environment native-only preparation (no UT/Go precompile)'
    value['on']['workflow_call']['inputs']={'environment':{'required':True,'type':'string'}}
    gate=value['jobs']['authorize'];gate['if']+=" && contains(fromJSON('[\"jed\",\"mnl2\",\"ruh\"]'), inputs.environment)"
    job=value['jobs']['native-only'];job['strategy']={'fail-fast':False,'matrix':{'node':['mo-standard-0']}}
    job['runs-on']="${{ format('cs-{0}-nc-n0-pr-v1', inputs.environment) }}"
    for step in job['steps']:
        if step['name']=='One-time native preparation system dependencies (separate cost)':
            check='test "$CS_CACHE_ENV" = mty'
            assert step['run'].count(check)==1
            step['run']=step['run'].replace(check,'test "$CS_CACHE_ENV" = \'${{ inputs.environment }}\'')
        if 'run' in step:step['run']=step['run'].replace('config/node-native-refresh-request.json',
            'config/node-native-uniform-request-${{ inputs.environment }}.json')
        if step['name']=='Require exact observed native key, CPU, tools and readonly node binding':
            step['run']=step['run'].replace('python3 .ci-workflow/scripts/node_compile_cache.py configure --catalog .ci-workflow/config/node-compile-cache-pr-catalog.json',
                'python3 .ci-workflow/scripts/node_cache_pvc_authority.py materialize\n'
                'python3 .ci-workflow/scripts/node_compile_cache.py configure --catalog "$RUNNER_TEMP/cs-reviewed-persistent-catalog.json"')
            step['run']=step['run'].replace('--catalog .ci-workflow/config/node-compile-cache-pr-catalog.json',
                '--catalog "$RUNNER_TEMP/cs-reviewed-persistent-catalog.json"')
        if step.get('with',{}).get('name','').startswith(('native-only-candidate-','native-refresh-evidence-')):
            step['with']['name']=step['with']['name'].replace('${{ matrix.node }}', '${{ inputs.environment }}-${{ matrix.node }}')
    return value


def render():
    return '# Generated by scripts/build_uniform_native_refresh_workflow.py; ordinary PR jobs unchanged.\n'+yaml.dump(
        build(),Dumper=old.consumer.Dumper,sort_keys=False,width=120)


if __name__=='__main__':print(render(),end='')
