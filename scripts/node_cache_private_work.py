"""Pure opt-in private work-volume template for NEW demand-driven readers.

Separates job writes from node root and from the persistent readonly cache.
This module does not deploy resources or alter existing pools. Protected live
validation must confirm generic-ephemeral provisioning, topology, disk gates,
queueing and owner-scoped workspace cleanup before enabling PR traffic.
"""
import copy

import incremental_cache as c

STORAGE_CLASS='directpv-min-io-ephemeral'


def apply(pod_spec,storage_class,size_gib=128):
    c.require(storage_class['metadata']['name']==STORAGE_CLASS
        and not storage_class['metadata'].get('deletionTimestamp')
        and storage_class['provisioner']=='directpv-min-io'
        and storage_class['volumeBindingMode']=='WaitForFirstConsumer'
        and storage_class['reclaimPolicy']=='Delete'
        and storage_class['parameters']['directpv.min.io/tier']=='ephemeral','private work storage contract differs')
    c.require(type(size_gib) is int and 80<=size_gib<=256,'private work volume budget differs')
    spec=copy.deepcopy(pod_spec)
    c.require(len(spec['containers'])==1 and spec['containers'][0]['name']=='runner'
        and not spec.get('initContainers') and spec['automountServiceAccountToken'] is False,
        'private work requires a new plain runner')
    volumes={v['name']:v for v in spec['volumes']}
    c.require(set(volumes)=={'work','cache'} and volumes['work']=={'name':'work','emptyDir':{}}
        and volumes['cache']['persistentVolumeClaim']['readOnly'] is True,'private work volume template differs')
    runner=spec['containers'][0]
    c.require(runner['resources']=={'requests':{'cpu':'7','memory':'12Gi'},'limits':{'cpu':'7','memory':'14Gi'}}
        and '@sha256:' in runner['image'],'private work runner image or resources differ')
    c.require(runner['volumeMounts']==[{'name':'work','mountPath':'/home/runner/_work'},
        {'name':'cache','mountPath':'/ci-cache','readOnly':True}],'private work mounts differ')
    c.require(not {'TMPDIR','GOTMPDIR','TEMP','TMP'} & {e['name'] for e in runner['env']},'conflicting temporary path override')
    # The scheduler/provisioner admits real storage capacity, not a hand-picked
    # runner count. PVC ownership is generated by Kubernetes for THIS Pod only;
    # the separate existing cache claim is never assigned an owner reference.
    spec['volumes']=[{'name':'work','ephemeral':{'volumeClaimTemplate':{'metadata':{'labels':{
        'codex.matrixorigin.io/purpose':'private-runner-work'}},'spec':{
        'accessModes':['ReadWriteOnce'],'volumeMode':'Filesystem','storageClassName':STORAGE_CLASS,
        'resources':{'requests':{'storage':str(size_gib)+'Gi'}}}}}},copy.deepcopy(volumes['cache'])]
    spec['securityContext']={'runAsUser':1001,'runAsGroup':1001,'fsGroup':1001,'fsGroupChangePolicy':'OnRootMismatch'}
    runner['volumeMounts'].append({'name':'work','mountPath':'/tmp','subPath':'.runner-private-tmp'})
    runner['env'] += [{'name':key,'value':'/tmp'} for key in ('TMPDIR','GOTMPDIR','TEMP','TMP')]
    spec['initContainers']=[{'name':'prepare-private-work','image':runner['image'],
        'command':['/bin/bash','-euc','mkdir -p /work/.runner-private-tmp; chmod 1777 /work/.runner-private-tmp'],
        'resources':{'requests':{'cpu':'100m','memory':'128Mi'},'limits':{'cpu':'1','memory':'512Mi'}},
        'securityContext':{'allowPrivilegeEscalation':False,'capabilities':{'drop':['ALL']}},
        'volumeMounts':[{'name':'work','mountPath':'/work'}]}]
    return spec
