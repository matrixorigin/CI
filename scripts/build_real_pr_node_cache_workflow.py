"""Isolated manual REAL-PR-head validation, never a production trigger change."""
import copy
import yaml
import build_pr_node_cache_workflow as consumer

TARGET='.github/workflows/node-cache-real-pr-validation.yaml'
CHECKOUT='actions/checkout@df4cb1c069e1874edd31b4311f1884172cec0e10'


def build():
    workflow=consumer.build();workflow['name']='Isolated current PR full UT - MTY two groups'
    call=workflow['on']['workflow_call']
    call['inputs']={'pr_number':{'type':'number','required':True},'expected_head_sha':{'type':'string','required':True}}
    workflow['jobs']['check_coverage_eligibility']={'runs-on':'ubuntu-latest','environment':'ci','timeout-minutes':5,
        'permissions':{'contents':'read','pull-requests':'read'},
        'outputs':{k:'${{ steps.authorize.outputs.'+k+' }}' for k in ('allowed','head_sha','head_repository','pr_number')},
        'steps':[{'uses':CHECKOUT,'with':{'repository':'${{ job.workflow_repository }}','ref':'${{ job.workflow_sha }}',
            'path':'.ci-workflow','persist-credentials':False,'sparse-checkout':'scripts\nconfig\n'}},
            {'name':'Authorize exact current open PR and trusted author (read-only)','id':'authorize',
             'env':{'REQUESTED_PR_NUMBER':'${{ inputs.pr_number }}','EXPECTED_PR_HEAD_SHA':'${{ inputs.expected_head_sha }}',
                    'CS_CACHE_READ_TOKEN':'${{ secrets.CS_COVERAGE_CACHE_READ_TOKEN || github.token }}'},
             'run':'python3 .ci-workflow/scripts/node_cache_real_pr_gate.py'},
            {'name':'Upload actual PR snapshot authorization','uses':'actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02',
             'with':{'name':'real-pr-snapshot-${{ github.run_id }}','path':'${{ runner.temp }}/real-pr-authorization.json',
                'if-no-files-found':'error'}}]}
    # This acceptance must exercise BOTH newly prepared nodes. General PRs
    # retain the demand label; deterministic validation avoids two groups being
    # assigned to one node and waiting for its private-PVC capacity unnecessarily.
    workflow['jobs']['ut-coverage-linux-x86']['runs-on']="${{ matrix.group == 0 && 'cs-mty-nc-n0-pr-v1' || 'cs-mty-nc-n1-pr-v1' }}"
    workflow['jobs']['merge-coverage-groups']['needs']=['check_coverage_eligibility','ut-coverage-linux-x86']
    replacements={'github.event.pull_request.head.repo.full_name':'needs.check_coverage_eligibility.outputs.head_repository',
        'github.event.pull_request.head.sha':'needs.check_coverage_eligibility.outputs.head_sha',
        'github.event.pull_request.number':'needs.check_coverage_eligibility.outputs.pr_number',
        'inputs.cache_seed':'false','inputs.bvt_generation':"''"}
    def replace(value):
        if isinstance(value,dict):return {k:replace(v) for k,v in value.items()}
        if isinstance(value,list):return [replace(v) for v in value]
        if isinstance(value,str):
            for before,after in replacements.items():value=value.replace(before,after)
        return value
    return replace(workflow)


def render():
    return '# Generated by scripts/build_real_pr_node_cache_workflow.py; no production entrypoint mutation.\n'+yaml.dump(
        build(),Dumper=consumer.Dumper,sort_keys=False,width=120)


if __name__=='__main__':print(render(),end='')
